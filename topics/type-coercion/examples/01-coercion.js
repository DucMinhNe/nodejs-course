console.log(0 == '');       // true
console.log(0 == '0');      // true
console.log('' == '0');     // false
console.log(null == undefined); // true
console.log(null === undefined); // false
console.log(NaN === NaN);   // false (always)
console.log([] == false);   // true
console.log([] == 0);       // true
console.log(1 + '2');       // '12'
console.log('1' - 2);       // -1
